"""
闰年判断, 输入一个年份(大于1582的整数):
    世纪闰年可以整除是400;
    假闰年既能整除100, 也能整除4;
    普通闰年能整除4;
    其他的，包含假闰年，都是平年;

    判断闰年不能只看“能否被4整除”，必须按照以下优先级顺序进行判断：
        ‌第一步：看能否被400整除？‌
            如果能，是‌闰年‌。（例如：2000年）
            如果不能，进入第二步。
        ‌第二步：看能否被100整除？‌
            如果能，是‌平年‌。（例如：1900年、2100年）
            如果不能，进入第三步。
        ‌第三步：看能否被4整除？‌
            如果能，是‌闰年‌。（例如：2024年、1996年）
            如果不能，是‌平年‌。（例如：2023年、1901年）
"""

def is_leap_year(year: int) -> bool:
    # 1. 基础校验
    if year <= 1582:
        raise ValueError("年份必须大于1582")

    # 2. 开始模式匹配
    # 我们构造了一个元组 (余数4, 余数100, 余数400) 作为匹配对象
    match (year % 4, year % 100, year % 400):

        # 情况 A: 世纪闰年 (能被400整除)
        # _ 表示“我不关心这个位置的值”，只要最后一个数是0就行
        case (_, _, 0):
            return True

        # 情况 B: 普通年份中的“假闰年” (能被100整除，但不能被400整除)
        # 这里前两个是0，最后一个不是0(因为上面已经拦截了0的情况)
        case (0, 0, _):
            return False

        # 情况 C: 普通闰年 (能被4整除，但不能被100整除)
        # 第一个是0，第二个不是0
        case (0, _, _):
            return True

        # 情况 D: 其他所有情况 (平年)
        # _ 是通配符，代表“剩下的所有情况”
        case _:
            return False


# 测试
if __name__ == "__main__":
    y = int(input("请输入一个年份(大于1582): "))
    print(f"{y} {'是' if is_leap_year(y) else '不是'}闰年")